import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');
const tokensPath = join(root, 'tokens.json');
const distDir = join(root, 'dist');

/** @param {unknown} node */
function isToken(node) {
  return (
    typeof node === 'object' &&
    node !== null &&
    '$value' in node &&
    typeof /** @type {{ $value: unknown }} */ (node).$value === 'string'
  );
}

/** @param {Record<string, unknown>} obj @param {string[]} path */
function flattenTokens(obj, path = []) {
  /** @type {Map<string, string>} */
  const result = new Map();

  for (const [key, value] of Object.entries(obj)) {
    if (key.startsWith('$')) continue;
    const nextPath = [...path, key];

    if (isToken(value)) {
      result.set(nextPath.join('.'), /** @type {{ $value: string }} */ (value).$value);
      continue;
    }

    if (typeof value === 'object' && value !== null) {
      for (const [k, v] of flattenTokens(/** @type {Record<string, unknown>} */ (value), nextPath)) {
        result.set(k, v);
      }
    }
  }

  return result;
}

/** @param {Map<string, string>} tokens */
function resolveReferences(tokens) {
  const resolved = new Map(tokens);

  const refPattern = /^\{([^}]+)\}$/;

  let changed = true;
  while (changed) {
    changed = false;
    for (const [key, value] of resolved) {
      const match = value.match(refPattern);
      if (!match) continue;
      const refKey = match[1];
      const refValue = resolved.get(refKey);
      if (refValue && !refValue.match(refPattern)) {
        resolved.set(key, refValue);
        changed = true;
      }
    }
  }

  return resolved;
}

/** @param {string} path */
function toCssVar(path) {
  return `--sg-${path.replace(/\./g, '-')}`;
}

/** @param {Map<string, string>} tokens */
function buildTokensCss(tokens) {
  const semanticKeys = [
    'color.semantic.background',
    'color.semantic.foreground',
    'color.semantic.muted',
    'color.semantic.border',
    'color.semantic.primary',
    'color.semantic.primary-foreground',
    'color.semantic.surface',
    'color.semantic.destructive',
    'color.semantic.focus-ring',
  ];

  const staticVars = [...tokens.entries()]
    .filter(([key]) => !key.startsWith('color.semantic.'))
    .map(([key, value]) => `  ${toCssVar(key)}: ${value};`)
    .join('\n');

  const lightSemantic = semanticKeys
    .map((key) => {
      const lightKey = `${key}.light`;
      const value = tokens.get(lightKey);
      const shortKey = key.replace('color.semantic.', '');
      return value ? `  --sg-color-${shortKey}: ${value};` : null;
    })
    .filter(Boolean)
    .join('\n');

  const darkSemantic = semanticKeys
    .map((key) => {
      const darkKey = `${key}.dark`;
      const value = tokens.get(darkKey);
      const shortKey = key.replace('color.semantic.', '');
      return value ? `  --sg-color-${shortKey}: ${value};` : null;
    })
    .filter(Boolean)
    .join('\n');

  return `/* Generated by @snapglow/design-tokens — do not edit */
:root {
${staticVars}
${lightSemantic}
  --sg-gradient-brand: linear-gradient(135deg, var(--sg-color-glow-gradient-start), var(--sg-color-glow-gradient-end));
}

[data-theme='dark'] {
${darkSemantic}
}
`;
}

/** @param {Map<string, string>} tokens */
function buildTailwindTheme(tokens) {
  const lines = ['/* Generated by @snapglow/design-tokens — do not edit */', '@theme {'];

  const themeMap = {
    '--color-brand-50': 'color.brand.50',
    '--color-brand-100': 'color.brand.100',
    '--color-brand-200': 'color.brand.200',
    '--color-brand-300': 'color.brand.300',
    '--color-brand-400': 'color.brand.400',
    '--color-brand-500': 'color.brand.500',
    '--color-brand-600': 'color.brand.600',
    '--color-brand-700': 'color.brand.700',
    '--color-brand-800': 'color.brand.800',
    '--color-brand-900': 'color.brand.900',
    '--color-background': 'color.semantic.background.light',
    '--color-foreground': 'color.semantic.foreground.light',
    '--color-muted': 'color.semantic.muted.light',
    '--color-border': 'color.semantic.border.light',
    '--color-primary': 'color.semantic.primary.light',
    '--color-primary-foreground': 'color.semantic.primary-foreground.light',
    '--color-surface': 'color.semantic.surface.light',
    '--color-destructive': 'color.semantic.destructive.light',
    '--color-focus-ring': 'color.semantic.focus-ring.light',
    '--font-sans': 'font.family.sans',
    '--font-mono': 'font.family.mono',
    '--radius-sm': 'radius.sm',
    '--radius-md': 'radius.md',
    '--radius-lg': 'radius.lg',
    '--radius-xl': 'radius.xl',
  };

  for (const [twVar, tokenKey] of Object.entries(themeMap)) {
    const value = tokens.get(tokenKey);
    if (value) lines.push(`  ${twVar}: ${value};`);
  }

  for (const [key, value] of tokens) {
    if (key.startsWith('spacing.')) {
      const name = key.replace('spacing.', '');
      lines.push(`  --spacing-${name}: ${value};`);
    }
    if (key.startsWith('font.size.')) {
      const name = key.replace('font.size.', '');
      lines.push(`  --text-${name}: ${value};`);
    }
  }

  lines.push('}');
  return `${lines.join('\n')}\n`;
}

async function main() {
  const raw = JSON.parse(await readFile(tokensPath, 'utf8'));
  const flat = flattenTokens(raw);
  const resolved = resolveReferences(flat);

  await mkdir(distDir, { recursive: true });
  await writeFile(join(distDir, 'tokens.css'), buildTokensCss(resolved));
  await writeFile(join(distDir, 'tailwind-theme.css'), buildTailwindTheme(resolved));
  console.log('Built design tokens → dist/tokens.css, dist/tailwind-theme.css');
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
